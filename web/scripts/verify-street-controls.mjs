import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { chooseStableWay, distancePointToPolyline, distancePointToSegment2D, findNearestNamedWay } from "../components/runtime/streetLogic.ts";

const road = (id, points, kind = "ROAD") => ({ id, name: id, aliases: [], kind, class: null, width_m: 8, points });
const a = road("A", [[0, 0], [100, 0]]);
const b = road("B", [[50, -50], [50, 50]]);
assert.equal(distancePointToSegment2D([5, 0], [0, 0], [10, 0]), 0);
assert.equal(distancePointToSegment2D([5, 3], [0, 0], [10, 0]), 3);
assert.equal(distancePointToSegment2D([15, 0], [0, 0], [10, 0]), 5);
assert.equal(distancePointToPolyline([5, 3], [[0, 0], [10, 0], [10, 10]]), 3);
assert.equal(findNearestNamedWay([10, 2], [a, b])?.way.id, "A");
assert.equal(findNearestNamedWay([10, 100], [a, b]), null);
assert.equal(chooseStableWay([50, 0], [a, b], null)?.way.id, "A");
assert.equal(chooseStableWay([51, 0], [a, b], "A")?.way.id, "A");
assert.equal(chooseStableWay([60, 0], [a, b], "B")?.way.id, "A");
const halves = [road("A", [[0, 0], [50, 0]]), road("A", [[50, 0], [100, 0]])];
assert.equal(chooseStableWay([49, 1], halves, "A")?.way.id, "A");
assert.equal(chooseStableWay([51, 1], halves, "A")?.way.id, "A");
const navigation = readFileSync(new URL("../components/runtime/NavigationController.tsx", import.meta.url), "utf8");
const interaction = readFileSync(new URL("../components/runtime/InteractionManager.tsx", import.meta.url), "utf8");
assert.match(navigation, /mode === "INSPECT" \? <MapControls/);
assert.match(navigation, /domElement=\{gl\.domElement\}/);
assert.match(navigation, /LEFT: THREE\.MOUSE\.PAN/);
assert.match(navigation, /RIGHT: THREE\.MOUSE\.ROTATE/);
assert.match(navigation, /enablePan=\{true\} enableRotate=\{true\} enableZoom=\{true\}/);
assert.match(navigation, /mode === "WALK" \? <WalkControls/);
assert.match(interaction, /isPrimarySelection\(event\.button, 0\)/);
assert.match(interaction, /isPrimarySelection\(event\.button, Math\.hypot/);
console.log("M19D.1 street math, hysteresis, tile continuity, control configuration PASS");
